let key = parseInt (prompt ("Ingrese una opcion de 1 a 5"));

switch (key) {
    case "1":
         console.log(`Selecciono la opcion 1 `);
        break;

        case "2":
        console.log(`Selecciono la opcion 2 `);
        break;

        case "3":
         console.log(`Selecciono la opcion 3 `);
        break;
        case "4":
        console.log(`Selecciono la opcion 4 `);
        break;
        case "5":
        console.log(`Selecciono la opcion 5 `);
        break;

    default:
        console.log(`Opcion invalida`);
        break;
}